export type PixelIconName = keyof typeof PIXEL_ICONS;

/** The lit cells of an icon, as (x, y) pairs. */
export function pixelCells(name: PixelIconName): { x: number; y: number }[] {
	const cells: { x: number; y: number }[] = [];
	PIXEL_ICONS[name].forEach((row, y) => {
		for (let x = 0; x < row.length; x++) if (row[x] === '#') cells.push({ x, y });
	});
	return cells;
}
